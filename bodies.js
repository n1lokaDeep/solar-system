/* Переводим расстояние спутника (км) в юниты сцены.
   Реальные орбиты в тысячи раз меньше планетных, поэтому
   используем сжатие: спутники раскладываются от 2,2 до 7 радиусов. */
export function moonOrbitUnits(distKm, index, total, planetVisualR){
  const t = total <= 1 ? 0.5 : index / (total - 1);
  // логарифмический шаг, чтобы внешние спутники не улетали слишком далеко
  const factor = 2.3 + Math.pow(t, 0.85) * 4.6;
  return planetVisualR * factor;
}
